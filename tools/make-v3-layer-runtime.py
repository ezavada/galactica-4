#!/usr/bin/env python3
"""Generate shipped layer lookup metadata and decode fallback pictures."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile
import zipfile
sys.dont_write_bytecode=True
ROOT=Path(__file__).resolve().parents[1]


def module(name, filename):
    spec=importlib.util.spec_from_file_location(name,ROOT/'tools'/filename)
    result=importlib.util.module_from_spec(spec);spec.loader.exec_module(result)
    return result


art=module('art','import-v3-art-resources.py')
presentation=module('presentation','import-v3-presentation.py')


def picture_path(number):
    if 2202<=number<=2212:return f'tech/blue-{number-2200:02d}.png'
    if number==2001:return 'events/labback.png'
    if number==2101:return 'events/labtop.png'
    return f'events/layers/pict-{number}.png'


def runtime(reference,main_source):
    rows={int(number):record['layers'] for number,record in reference['layers'].items()}
    rows[0]=art.layers(presentation.resource(main_source,'Layr',0))
    result={str(number):[{'picture':r['picture'],'path':picture_path(r['picture']),
                         'mode':r['mode'],'background':r['background']} for r in layers]
            for number,layers in sorted(rows.items())}
    return '// Generated by tools/make-v3-layer-runtime.py; edit the importer/source, not this file.\nmodule.exports='+json.dumps(result,separators=(',',':'))+';\n'


def generate(source):
    archive=source/'release/gad-3.0.2-cdrom.zip'
    reference=art.import_reference(archive)
    main=(source/'Resources/gal-mainrsrc.r').read_bytes().decode('mac_roman')
    metadata=runtime(reference,main)
    (ROOT/'src/js/shipped-art-layers.js').write_text(metadata)
    with zipfile.ZipFile(archive) as z:
        inventory=art.resources(art.resource_fork(z.read(reference['appleDoubleEntry'])))
    nonmodule=(source/'Resources/gal-non-module.r').read_bytes().decode('mac_roman')
    inventory[('PICT',100)]=presentation.resource(nonmodule,'PICT',100)
    wanted={r['picture'] for rows in json.loads(metadata.split('module.exports=')[1][:-2]).values() for r in rows}
    destination=ROOT/'data/events/layers';destination.mkdir(parents=True,exist_ok=True)
    magick=shutil.which('magick')
    if not magick:raise RuntimeError('ImageMagick required to decode fallback PICTs')
    provenance={'archive':archive.name,'archiveSha256':reference['archiveSha256'],
                'genericSource':'Resources/gal-non-module.r PICT100','pictures':{}}
    with tempfile.TemporaryDirectory(prefix='galactica-layer-export-') as directory:
        for number in sorted(wanted):
            if not picture_path(number).startswith('events/layers/'):continue
            payload=inventory[('PICT',number)]
            pict=Path(directory)/f'{number}.pict';pict.write_bytes(b'\0'*512+payload)
            png=ROOT/'data'/picture_path(number)
            subprocess.run([magick,str(pict),str(png)],check=True,capture_output=True)
            top,left,bottom,right=struct.unpack_from('>hhhh',payload,2)
            provenance['pictures'][str(number)]={'pictSha256':hashlib.sha256(payload).hexdigest(),
                'pngSha256':hashlib.sha256(png.read_bytes()).hexdigest(),'width':right-left,'height':bottom-top,
                'pngWidth':struct.unpack_from('>I',png.read_bytes(),16)[0],
                'pngHeight':struct.unpack_from('>I',png.read_bytes(),20)[0]}
    (destination/'provenance.json').write_text(json.dumps(provenance,indent=2)+'\n')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('source',type=Path)
    generate(parser.parse_args().source)
