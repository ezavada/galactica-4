#!/usr/bin/env node
// Refresh the art gallery's browser-readable layer definitions from the game.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const layers=require(path.join(root,'src/js/shipped-art-layers.js'));
const dest=path.join(root,'data/art-styles/gallery-layers.js');
fs.writeFileSync(dest,'// Generated by tools/build-art-gallery.cjs from src/js/shipped-art-layers.js.\nwindow.GALACTICA_ART_LAYERS = '+JSON.stringify(layers)+';\n');
console.log('Updated gallery layer definitions.');
